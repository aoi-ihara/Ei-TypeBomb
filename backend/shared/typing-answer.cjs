const ANSWER_CHAR = /^[a-zA-Z0-9 ,.?!\-、。！？ー]$/u;
// Keep authoring validation aligned with the game romanization dictionary.
const SUPPORTED_KANA = new Set(
    Object.values(ROMAJI).flatMap((value) => Array.from(value)),
);
const allowedAnswerChar = (char) =>
    ANSWER_CHAR.test(char) || SUPPORTED_KANA.has(char);

function isAllowedTypingAnswer(value) {
    return (
        typeof value === "string" &&
        value.length > 0 &&
        Array.from(value).every(allowedAnswerChar)
    );
}

/** @param {{ answer: string, readings?: unknown }} item */
function getTypingAnswer(item) {
    const first = Array.isArray(item.readings) ? item.readings[0] : undefined;
    if (typeof first === "string" && /^[ぁ-ゖー]+$/u.test(first) && isAllowedTypingAnswer(first)) {
        return first;
    }
    return isAllowedTypingAnswer(item.answer) ? item.answer : null;
}

module.exports = { ROMAJI, allowedAnswerChar, isAllowedTypingAnswer, getTypingAnswer };
